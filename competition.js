function getCurrentEventKey() {
  const urlParams = new URLSearchParams(window.location.search);
  const eventParam = urlParams.get("event");
  if (eventParam && competitionDatabase[eventParam]) {
    return eventParam;
  }
  return "renegade";
}

function switchEvent(eventKey) {
  const newUrl = `${window.location.pathname}?event=${eventKey}`;
  window.history.pushState({ path: newUrl }, "", newUrl);
  populateCompetitionView(eventKey);
}

function populateCompetitionView(eventKey) {
  const data = competitionDatabase[eventKey];
  if (!data) return;

  const selectElem = document.getElementById("contestSelect");
  if (selectElem) selectElem.value = eventKey;

  const isRecap = data.tag.includes("RECAP");

  // Headers
  document.getElementById("contestTitle").textContent = data.title;
  document.getElementById("contestSubtitle").textContent = data.subtitle;
  document.getElementById("contestTag").textContent = data.tag;
  document.getElementById("bandCountBadge").textContent = `${data.roster.length} Programs`;

  // UI labels for recap vs upcoming draw
  document.getElementById("rosterTitle").innerHTML = isRecap 
    ? `<i data-lucide="list-ordered" class="w-4 h-4 text-indigo-400"></i> Prelims & Division Flight Draw`
    : `<i data-lucide="list-ordered" class="w-4 h-4 text-indigo-400"></i> Registered Prelims Flight Draw`;

  document.getElementById("leaderboardTitle").innerHTML = isRecap
    ? `<i data-lucide="award" class="w-4 h-4 text-emerald-400"></i> Official Verified Leaderboard & Recaps`
    : `<i data-lucide="trending-up" class="w-4 h-4 text-emerald-400"></i> Model Predicted Leaderboard`;

  document.getElementById("leaderboardBadge").textContent = isRecap ? "Official Scores" : "Model Projections";
  document.getElementById("colScore").textContent = isRecap ? "Official Score" : "Predicted Score";
  document.getElementById("colStatus").textContent = isRecap ? "Division / Status" : "Projected Status";

  // Spotlight Box
  document.getElementById("fhcEventHeadline").textContent = data.fhcHeadline;
  document.getElementById("fhcEventSummary").textContent = data.fhcSummary;
  document.getElementById("fhcStatPeak").textContent = data.fhcPeak;
  document.getElementById("fhcStatPeakSub").textContent = data.fhcPeakSub;
  document.getElementById("fhcStatTarget").textContent = data.fhcTarget;
  document.getElementById("fhcStatTargetSub").textContent = data.fhcTargetSub;
  document.getElementById("fhcStatRank").textContent = data.fhcRank;
  document.getElementById("fhcStatCutoff").textContent = data.fhcCutoff;
  document.getElementById("fhcStatCutoffSub").textContent = data.fhcCutoffSub;

  document.getElementById("statLabel1").textContent = isRecap ? "Achieved Score" : "Historical Peak";
  document.getElementById("statLabel2").textContent = isRecap ? "Class / Caption" : "Target Score";
  document.getElementById("statLabel3").textContent = isRecap ? "Official Placement" : "Projected Place";
  document.getElementById("statLabel4").textContent = isRecap ? "Champion Score" : "Finals Benchmark";

  // Render Roster
  const rosterBody = document.getElementById("rosterTableBody");
  rosterBody.innerHTML = "";
  data.roster.forEach((band, idx) => {
    const isFHC = band.name.includes("Howell Central");
    const tr = document.createElement("tr");
    tr.className = isFHC ? "bg-blue-950/40 border-l-2 border-blue-400" : "hover:bg-slate-900/60 transition";
    tr.innerHTML = `
      <td class="py-2.5 px-3 font-mono text-slate-500">${idx + 1}</td>
      <td class="py-2.5 px-3 ${isFHC ? 'text-blue-300 font-bold flex items-center gap-1.5' : 'text-slate-200'}">
        ${band.name}
        <span class="text-[10px] text-slate-500 font-mono font-normal">(${band.state})</span>
        ${isFHC ? '<span class="text-[9px] bg-blue-500/20 text-blue-300 px-1.5 py-0.5 rounded font-mono font-bold">FHC</span>' : ''}
      </td>
      <td class="py-2.5 px-3 text-right text-slate-400 font-mono text-[11px]">${band.flight}</td>
    `;
    rosterBody.appendChild(tr);
  });

  // Render Leaderboard (Sorted by score descending)
  const leaderboardBody = document.getElementById("leaderboardTableBody");
  leaderboardBody.innerHTML = "";
  const sorted = [...data.roster].sort((a, b) => b.base - a.base);

  sorted.forEach((band, idx) => {
    const rank = idx + 1;
    const isFHC = band.name.includes("Howell Central");
    const isTopTier = rank <= 12;

    const tr = document.createElement("tr");
    tr.className = isFHC
      ? "bg-blue-950/40 border-l-2 border-blue-400"
      : isTopTier
      ? "hover:bg-slate-900/50 transition"
      : "hover:bg-slate-900/30 opacity-70 transition";

    tr.innerHTML = `
      <td class="py-2.5 px-3 font-mono font-bold ${rank <= 3 ? 'text-amber-400' : 'text-slate-400'}">
        #${rank}
      </td>
      <td class="py-2.5 px-3 ${isFHC ? 'text-blue-300 font-bold' : 'text-white'}">
        ${band.name} <span class="text-[10px] text-slate-500 font-mono font-normal">(${band.state})</span>
      </td>
      <td class="py-2.5 px-3 text-right font-mono font-bold text-emerald-400">
        ${band.base.toFixed(3).replace(/\.?0+$/, (match, offset, string) => match.length === 4 ? '.000' : match)}
      </td>
      <td class="py-2.5 px-3 text-right">
        ${
          isRecap
            ? `<span class="text-[10px] bg-slate-800 text-slate-300 px-2 py-0.5 rounded font-mono">${band.flight}</span>`
            : (isTopTier 
                ? '<span class="text-[10px] bg-emerald-500/10 text-emerald-400 border border-emerald-500/20 px-1.5 py-0.5 rounded font-mono font-semibold">Finals Lock</span>' 
                : '<span class="text-[10px] bg-slate-800 text-slate-400 px-1.5 py-0.5 rounded font-mono">Prelims</span>')
        }
      </td>
    `;
    leaderboardBody.appendChild(tr);
  });

  // Render Highlights
  const historyContainer = document.getElementById("historicalContestStats");
  historyContainer.innerHTML = "";
  data.historicalHighlights.forEach(stat => {
    const card = document.createElement("div");
    card.className = "p-3.5 bg-slate-950/60 rounded-xl border border-slate-800/80";
    card.innerHTML = `
      <div class="text-[11px] uppercase tracking-wider text-slate-400 font-bold">${stat.label}</div>
      <div class="text-base font-black text-slate-100 font-mono mt-0.5">${stat.value}</div>
      <div class="text-[10px] text-slate-500 mt-0.5">${stat.sub}</div>
    `;
    historyContainer.appendChild(card);
  });

  lucide.createIcons();
}

window.addEventListener("popstate", () => {
  populateCompetitionView(getCurrentEventKey());
});

document.addEventListener("DOMContentLoaded", () => {
  lucide.createIcons();
  populateCompetitionView(getCurrentEventKey());
});